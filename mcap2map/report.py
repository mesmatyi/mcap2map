"""README.md of a run, generated from the run's own outputs, logs and stage markers."""
import json
import os
import re
import time

import numpy as np

POS_TYPES = {16: "SINGLE", 17: "PSRDIFF", 18: "SBAS", 32: "L1_FLOAT", 34: "NARROW_FLOAT", 48: "L1_INT", 49: "WIDE_INT",
             50: "NARROW_INT (RTK fixed)", 52: "INS_SBAS", 53: "INS_PSRSP (single point)", 54: "INS_PSRDIFF (DGPS)",
             55: "INS_RTKFLOAT", 56: "INS_RTKFIXED"}


def _grep(text, pattern, default=None, cast=None, last=True):
    m = re.findall(pattern, text, re.M)
    if not m:
        return default
    v = m[-1] if last else m[0]
    return cast(v) if cast else v


def _pcd_points(path):
    if not os.path.exists(path):
        return None
    with open(path, "rb") as f:
        h = f.read(400).decode("latin1")
    return int(re.search(r"POINTS (\d+)", h).group(1))


def _rtk_agreement(run):
    try:
        g = np.load(os.path.join(run.cache, "gnss_epochs.npz"))
        z = np.load(os.path.join(run.cache, "traj_refined_1khz.npz"))
        t0, dt, pos = float(z["t0"]), float(z["dt"]), z["pos"]
        m = (g["type"] == 50) & (np.hypot(g["std"][:, 0], g["std"][:, 1]) < 0.03)
        i = np.clip(np.round((g["t"][m] - t0) / dt).astype(int), 0, len(pos) - 1)
        d = pos[i] - g["p_base"][m]
        h = np.linalg.norm(d[:, :2], axis=1)
        return {"n": int(m.sum()), "h_med_cm": float(np.median(h) * 100), "h_p95_cm": float(np.percentile(h, 95) * 100),
                "v_p95_cm": float(np.percentile(np.abs(d[:, 2]), 95) * 100)} if m.sum() > 20 else None
    except Exception:
        return None


def write(run):
    cfg = run.cfg
    F = cfg["frame"]
    L = []
    w = L.append
    info = json.load(open(os.path.join(run.cache, "traj_info.json")))
    wins_p = os.path.join(run.cache, "lo_windows_used.json")
    wins = json.load(open(wins_p)) if os.path.exists(wins_p) else []
    log = {s: run.logtext(s) for s in ("refine", "map", "colorize", "lanelet", "checks", "reference")}
    o = run.output
    n01, n02 = _pcd_points(f"{o}/pointcloud_map.pcd"), _pcd_points(f"{o}/pointcloud_map_0.2m.pcd")
    nrgb = _pcd_points(f"{o}/pointcloud_map_rgb.pcd")
    ntiles = len([f for f in os.listdir(f"{o}/pointcloud_map_tiles") if f.endswith(".pcd")]) \
        if os.path.isdir(f"{o}/pointcloud_map_tiles") else 0
    has_ll = os.path.exists(f"{o}/lanelet2_map.osm")
    bag = os.path.basename(cfg["bag"])

    w(f"# Maps from `{bag}`\n")
    w(f"Generated by mcap2map on {time.strftime('%Y-%m-%d %H:%M')} without manual steps. Route "
      f"{info['route_length_m']/1000:.2f} km, {info['duration_s']:.0f} s. Run directory: `{run.out}`.\n")
    w("## Coordinate system (shared by every file here)\n")
    w("| | |\n|---|---|")
    w(f"| frame | `{F['name']}` ({F['origin_choice']}) |")
    w(f"| x / y | {F['utm_epsg']} easting − {F['ox']:.1f} m / northing − {F['oy']:.1f} m (WGS84) |")
    w(f"| z | NovAtel orthometric height = WGS84 ellipsoidal height − {F['undulation']:.2f} m |")
    w(f"| Lanelet2 projector | `UtmProjector(Origin({F['lat0']}, {F['lon0']}))`, Autoware `LocalCartesianUTM` "
      f"(`map_projector_info.yaml`) |\n")

    w("## Files\n")
    w("| file | content |\n|---|---|")
    if n01:
        w(f"| `pointcloud_map.pcd` | 0.1 m voxels, {n01:,} points, `x y z intensity` (lidar reflectivity), moving objects removed |")
        w(f"| `pointcloud_map_0.2m.pcd` | 0.2 m voxels, {n02:,} points |")
        w(f"| `pointcloud_map_tiles/` | {ntiles} tiles of 100 m + `pointcloud_map_metadata.yaml` (Autoware dynamic loading) |")
    if nrgb:
        w(f"| `pointcloud_map_rgb.pcd` | coloured from the cameras, {nrgb:,} points, `x y z rgb intensity` |")
        w("| `pointcloud_map_rgb_0.2m.pcd` | coloured map at 0.2 m |")
    if has_ll:
        w(f"| `lanelet2_map.osm` | Lanelet2 map of the driven roads |")
    w("| `map_projector_info.yaml` | Autoware projector |")
    w("| `calibration.json` | sensor calibration estimated from this recording |")
    w("| `trajectory_base_link_map_frame.csv` | refined base_link trajectory, 10 Hz |")
    w("| `validation/` | validator output, routing test, overlays, close-ups, overviews |\n")

    w("## Sensors used\n")
    T = cfg["topics"]
    w(f"* GNSS/INS: `{T['bestutm']}`, `{T['fix']}`, `{T['odom']}`; lidar: `{T['points']}` "
      f"({cfg['lidar']['points_per_scan']} points/scan)")
    for c in cfg["cameras"]:
        w(f"* camera `{c['name']}`: `{c['image_topic']}` ({c['kind']} {c['encoding']}, {c['width']}×{c['height']})")
    w(f"* vehicle profile: {cfg.get('profile') or 'none (calibration started from /tf_static)'}\n")

    w("## Trajectory\n")
    segs = info["gnss_segments"]
    good_t = sum(s["t1"] - s["t0"] for s in segs if s["type"] in (50, 56) and s["std_h_median"] < 0.1)
    w(f"* GNSS: RTK-good (fixed, std < 10 cm) for {info['rtk_good_fraction']*100:.0f} % of the epochs. Solution types: "
      + ", ".join(f"{POS_TYPES.get(t, t)} {sum(s['t1'] - s['t0'] for s in segs if s['type'] == t):.0f} s"
                  for t in sorted({s['type'] for s in segs})) + ".")
    if wins:
        w(f"* Lidar odometry replaces the receiver solution in {len(wins)} degraded-GNSS window(s): "
          + ", ".join(f"{x['t_rel'][0]:.1f}–{x['t_rel'][1]:.1f} s" for x in wins) + ".")
    else:
        w("* No degraded-GNSS window: the receiver solution is the reference everywhere.")
    it_seq = _grep(log["refine"], r"^iteration \d+ seq: (.*)$")
    it_rev = _grep(log["refine"], r"^iteration \d+ rev: (.*)$")
    corr = _grep(log["refine"], r"^\s+corrections (.*)$")
    w(f"* Pose graph (lidar submaps 10 m / 25 m apart + revisits, GNSS priors by solution quality): sequential {it_seq}; "
      f"revisits {it_rev}.")
    if corr:
        w(f"* Corrections to the reference: {corr.split(' | GNSS')[0]}.")
    ra = _rtk_agreement(run)
    if ra:
        w(f"* Agreement with RTK-fixed epochs: {ra['h_med_cm']:.1f} cm horizontal median (p95 {ra['h_p95_cm']:.1f} cm), "
          f"vertical p95 {ra['v_p95_cm']:.1f} cm ({ra['n']} epochs).")
    w("")

    w("## Calibration (details in `calibration.json`)\n")
    cl = json.load(open(os.path.join(run.cache, "calib_refined.json")))
    w(f"* GNSS antenna in base_link: {', '.join(f'{x:.3f}' for x in info['lever_arm'])} m ({info['lever_arm_source']}).")
    w(f"* INS heading offset: {cfg.get('ins_heading_offset_deg', 0):+.2f}° (course over ground − INS yaw on straight "
      f"RTK driving; the INS body frame is rotated this much against the vehicle axis).")
    w(f"* Lidar vs /tf_static (INS frame): yaw {cl['yaw_deg']:+.2f}°, pitch {cl['pitch_deg']:+.2f}°, roll "
      f"{cl['roll_deg']:+.2f}°; stamp offset {cl['dt_lidar_ms']:+.1f} ms.")
    cc_p = os.path.join(run.cache, "cam_calib.json")
    if os.path.exists(cc_p):
        for cc in json.load(open(cc_p))["cameras"]:
            hs = cc.get("heldout_spread")
            w(f"* Camera `{cc['name']}`: stamp offset {cc['dt_cam_ms']:+.0f} ms, rotation {np.round(cc['rot_deg_cam'], 2).tolist()}° "
              f"from {cc['start']}, model {cc['model']}"
              + (f"; photo-consistency {cc.get('heldout_spread_start', float('nan')):.3f} → {hs:.3f}" if hs else "; not calibrated") + ".")
    w("")

    w("## Point cloud maps\n")
    dyn = _grep(log["map"], r"dynamic removed \d+ \(([\d.]+)%\)")
    if dyn:
        w(f"* {dyn} % of the voxels removed as moving objects (free-space voting).")
    if nrgb:
        dc = _grep(log["colorize"], r"directly coloured: \d+ / \d+ \(([\d.]+)%\)")
        fn = _grep(log["colorize"], r"filled from neighbours: \d+ \(([\d.]+)%\)")
        gr = _grep(log["colorize"], r"reflectivity grey: \d+ \(([\d.]+)%\)")
        w(f"* Colour: {dc} % of points directly from camera pixels, {fn} % from the nearest coloured neighbour, "
          f"{gr} % reflectivity grey.")
    w("")

    if has_ll:
        ll = log["lanelet"]
        w("## Lanelet2 map\n")
        w(f"* {_grep(ll, r'^wrote \S+: (.*)$')}.")
        for pat in (r"^(roundabout lanelets: .*)$", r"^(junction connectors: \d+ at \d+ junctions)", r"^(traffic light regulatory elements: \d+)",
                    r"^(crosswalk lanelets: \d+)"):
            v = _grep(ll, pat)
            if v:
                w(f"* {v}.")
        n_traj = _grep(ll, r"^(\d+) pieces re-modelled from the driven path", "0")
        n_fb = _grep(ll, r"re-modelled from it: (\d+ \(\+\d+ neighbours\))", "0")
        w(f"* Lane geometry: painted lines fitted to the PCD paint; unpainted pieces ({n_traj}) and pieces whose fitted lanes "
          f"missed the driven path ({n_fb}) are centred on the driven path (3.5 m lanes).")
        w("* OSM: lane counts, directions, turn restrictions, speed limits, signals; roundabouts mapped completely.")
        rep = []
        v = _grep(ll, r"^junction clusters: (\d+) short chain")
        if v:
            rep.append(f"{v} short OSM chain(s) between junction nodes merged into one junction")
        for m_ in re.finditer(r"^junction relocation: chain \d+ \(([^,]+), leaving the node \d+ deg off it\) runs (\d+) m "
                              r"inside chain \d+ \(([^)]+)\) from OSM node \d+; junction moved to \(([-\d.]+), ([-\d.]+)\)",
                              ll, re.M):
            rep.append(f"{m_.group(1)} runs {m_.group(2)} m along {m_.group(3)} in OSM: junction moved to "
                       f"({m_.group(4)}, {m_.group(5)})")
        for m_ in re.finditer(r"^roundabout chain \d+: flare node \d+ lies ([-+\d.]+) m outside the measured kerb; arm "
                              r"rebuilt: .* at \(([-\d.]+), ([-\d.]+)\), links .* follow the (.*) path to the kerb", ll, re.M):
            kinds = m_.group(4).split(" / ")
            how = ("both links follow the driven paths" if all(k_ == "driven" for k_ in kinds) else
                   f"links: {' / '.join(kinds)} (straight = continuation of the approach lane, not driven)")
            rep.append(f"roundabout arm whose OSM split node lies at the measured kerb ({m_.group(1)} m) rebuilt from "
                       f"({m_.group(2)}, {m_.group(3)}); {how}")
        v = _grep(ll, r"^connectors added for driven manoeuvres without a route: (\d+)")
        if v and v != "0":
            rep.append(f"{v} connector(s) added for driven manoeuvres without a route (`mcap2map:driven_manoeuvre=yes`)")
        if rep:
            w("* OSM geometry repaired (details in `logs/lanelet.log`):")
            for r_ in rep:
                w(f"  * {r_}.")
        w("")
        ck = log["checks"]
        w("## Validation\n")
        w("| check | result |\n|---|---|")
        mk = run.done("checks") or {}
        val = (mk.get("metrics") or {}).get("validator")
        w(f"| Autoware lanelet2 map validator | {json.dumps(val) if val else 'not run'} |")
        w(f"| route test (driven path every 50 m) | {_grep(ck, r'^(route segments of 50 m: .*)$', 'n/a')}; "
          f"{_grep(ck, r'^(full route .*)$', '')} |")
        w(f"| driven positions in a lanelet of matching direction | {_grep(ck, r'matching direction: ([\d.]+% of \d+)', 'n/a')} |")
        w(f"| painted boundaries vs PCD paint | {_grep(ck, r'^paint: (.*)$', 'n/a')} |")
        w(f"| smoothness | {_grep(ck, r'boundaries >= 30 m; (.*)$', 'n/a')} |")
        w(f"| kinks > 40° | {_grep(ck, r'turn > 40.0 deg between consecutive segments: (\d+)', 'n/a')} |")
        w(f"| connectors | {_grep(ck, r'^(\d+ connectors; flagged.*)$', 'n/a')} |\n")

    w("## Limitations\n")
    if wins:
        w(f"* In the degraded-GNSS window(s) ({', '.join(f'{x['t_rel'][0]:.0f}–{x['t_rel'][1]:.0f} s' for x in wins)}) the "
          "trajectory is lidar odometry anchored by RTK at the window ends: locally sharp, absolute position only good to "
          "decimetres–metres in the middle of long windows.")
    if has_ll:
        w("* Lanes on unpainted streets follow the driven path (3.5 m assumed), not measured kerbs; where OSM counts more "
          "lanes than the street has, extra lanes are stacked beside the driven one.")
        w("* Traffic-light head positions are placeholders (`approximate_position=yes`); no yield / right-of-way elements.")
        if isinstance(val, dict) and any(k.startswith("Error") for k in val):
            w(f"* Validator errors remain: {', '.join(k for k in val if k.startswith('Error'))} (see `validation/autoware_validator`).")
    w("* Only the driven roads are mapped.\n")

    w("## Stages\n")
    w("| stage | seconds | finished |\n|---|---|---|")
    from .pipeline import STAGES
    for s in STAGES:
        d = run.done(s)
        if d:
            w(f"| {s} | {d['seconds']:.0f} | {d['finished']} |")
    w(f"\nRe-run or resume: `python -m mcap2map run {cfg['bag']} --out {run.out}` (add `--from <stage>` to redo a "
      "stage and everything after it).")
    open(os.path.join(o, "README.md"), "w").write("\n".join(L) + "\n")
